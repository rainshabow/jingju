/**
 * AI 分析用的 Prompt 模板。
 * 每个 Prompt 对应一步分析 Pipeline。
 */

// ── Step 1: 角色行当提取 ──
export const CHARACTER_PROMPT = `
你是一位京剧剧本分析专家。请从以下剧本中提取所有角色，
并基于角色的性别、年龄、身份、性格描述及唱念做打等表演提示，
推断其行当归属（生、旦、净、丑及细分类别）。

分析规则：
- **生**：男性角色。唱念为主 → 老生；年轻俊秀 → 小生；武打为主 → 武生
- **旦**：女性角色。端庄贵重 → 青衣；活泼年轻 → 花旦；年长女性 → 老旦；文武并重 → 花衫
- **净**：性格强烈男性。唱功厚重 → 铜锤花脸；做派武打 → 架子花
- **丑**：喜剧或反面角色。文场 → 文丑；武场 → 武丑

角色推断依据：
1. 性别直接决定生/旦大类
2. 身份高贵（帝王/统帅/大将）→ 老生、净类的概率高
3. 唱词比例大 → 偏向唱功行当
4. 武打/走边/趟马等动作 → 偏向武行当

请输出每个角色的 name、gender、age_group、identity、personality、performance_style、role_type、role_subtype、confidence（推断置信度 0-1）。

剧本文本：
{playText}
`.trim();

// ── Step 2: 关系提取 ──
export const RELATION_PROMPT = `
你是一位京剧剧本关系分析专家。基于以下角色列表和剧本全文，
提取所有角色之间的互动关系。

角色列表：
{characterList}

关系类型包括：夫妻、父子、兄弟、君臣、敌对、同营、师徒、军务、宗亲。
互动强度（0-1）：基于对白共现频率、情节重要程度。

输出每条关系：char_a、char_b、relation_type、strength、evidence（原文依据）。

剧本文本：
{playText}
`.trim();

// ── Step 3: 主题提取 + 剧本分类 ──
